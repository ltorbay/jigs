#!/bin/sh
# Regenerate openspec/specs/INDEX.md from each spec's Purpose line.
#
# Install as tools/spec_index.sh. The index is the one-file view agents grep to
# find the right spec; the spec-index meta-suite (tests/meta/spec_index_suite.gd)
# fails when a spec has a TBD/missing Purpose, is absent from the index, or when
# an index line drifted from its spec. `openspec archive` never touches the
# index and writes created specs with a placeholder Purpose, so run this after
# every archive that created a spec (the archive_spec_check hook reminds you).
set -eu
cd "$(dirname "$0")/.."
out="openspec/specs/INDEX.md"
{
  echo "# Spec Index"
  echo
  echo "Generated by \`tools/spec_index.sh\` from each spec's Purpose line; do not edit by hand. The spec-index meta-suite tripwires drift."
  echo
  for d in openspec/specs/*/; do
    name=$(basename "$d")
    purpose=$(awk '/^## Purpose/{found=1; next} found && NF {print; exit}' "$d/spec.md")
    echo "- **$name** — $purpose"
  done
} > "$out"
echo "Wrote $out ($(grep -c '^- ' "$out") specs)"
